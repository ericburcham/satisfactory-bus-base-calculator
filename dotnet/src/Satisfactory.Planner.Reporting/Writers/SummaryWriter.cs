using Satisfactory.Planner.Core.Configuration;
using Satisfactory.Planner.Core.Progression;
using Satisfactory.Planner.Core.Tiers;
using Satisfactory.Planner.Reporting.Formatting;
using Satisfactory.Planner.Reporting.IO;

namespace Satisfactory.Planner.Reporting.Writers;

/// <summary>
/// Writes <c>summary.txt</c>, one line per tier with running totals (Python <c>main</c> lines 925-944).
/// </summary>
/// <remarks>
/// Per tier: the new items, new machines, alternate recipes among the new machine groups, reused machines' worth, power
/// used, and the change in raw input (excluding water); then the running totals of machines, power used and power
/// generated, and the tier's total raw input (excluding water). The raw and reused sums reproduce Python 3.12+
/// <c>sum()</c>, which adds floats with compensated summation; the running totals use plain <c>+=</c> as the Python does.
/// </remarks>
public sealed class SummaryWriter : ISummaryWriter
{
    /// <summary>The summary's file name.</summary>
    private const string FileName = "summary.txt";

    private readonly IFileSystem _fileSystem;
    private readonly string _newLine;

    /// <summary>Creates the writer.</summary>
    /// <param name="fileSystem">The file system the summary is written to.</param>
    /// <param name="newLine">The line terminator written after every line (the CLI passes <see cref="Environment.NewLine"/>).</param>
    public SummaryWriter(IFileSystem fileSystem, string newLine)
    {
        ArgumentNullException.ThrowIfNull(fileSystem);
        ArgumentNullException.ThrowIfNull(newLine);
        _fileSystem = fileSystem;
        _newLine = newLine;
    }

    /// <inheritdoc />
    public string Write(IReadOnlyList<(TierResult Result, TierTotals Totals)> tiers, string outputFolder)
    {
        ArgumentNullException.ThrowIfNull(tiers);
        ArgumentNullException.ThrowIfNull(outputFolder);
        var lines = new List<string>
        {
            "TIER SUMMARY (machines rounded up, 100% clock; extractors excluded; raw excludes water)",
            string.Empty,
            string.Join(
                ' ',
                PythonTextFormat.PadRight("Tier", 22),
                PythonTextFormat.PadLeft("new items", 9),
                PythonTextFormat.PadLeft("new machines", 12),
                PythonTextFormat.PadLeft("alts", 5),
                PythonTextFormat.PadLeft("reused", 7),
                PythonTextFormat.PadLeft("new MW", 10),
                PythonTextFormat.PadLeft("raw +/min", 10),
                "|",
                PythonTextFormat.PadLeft("total machines", 14),
                PythonTextFormat.PadLeft("total MW", 10),
                PythonTextFormat.PadLeft("nuclear MW", 10),
                PythonTextFormat.PadLeft("total raw/min", 13)),
            "  (reused = machines' worth of spare capacity from earlier tiers put to work;"
                + " MW = power used; nuclear MW = power generated by the plants built so far)",
            string.Empty,
        };

        long totalMachines = 0;
        double totalUsed = 0.0;
        double totalGenerated = 0.0;
        double previousRaw = 0.0;
        foreach ((TierResult result, TierTotals totals) in tiers)
        {
            ArgumentNullException.ThrowIfNull(result, nameof(tiers));
            ArgumentNullException.ThrowIfNull(totals, nameof(tiers));
            totalMachines += totals.NewMachines;
            totalUsed += totals.PowerUsedMw;
            totalGenerated += totals.PowerGeneratedMw;
            double raw = RawExcludingWater(result);
            int alternates = result.NewMachines.Keys.Count(rc => result.Recipes[rc].IsAlternate);
            lines.Add(string.Join(
                ' ',
                PythonTextFormat.PadRight(TierNames.For(result.Tier), 22),
                PythonNumberFormat.Integer(result.NewItems.Count, 9),
                PythonNumberFormat.Integer(totals.NewMachines, 12),
                PythonNumberFormat.Integer(alternates, 5),
                PythonNumberFormat.Fixed(Reused(result), 1, 7),
                PythonNumberFormat.FixedThousands(totals.PowerUsedMw, 0, 10),
                PythonNumberFormat.FixedThousands(raw - previousRaw, 0, 10),
                "|",
                PythonNumberFormat.Integer(totalMachines, 14),
                PythonNumberFormat.FixedThousands(totalUsed, 0, 10),
                PythonNumberFormat.FixedThousands(totalGenerated, 0, 10),
                PythonNumberFormat.FixedThousands(raw, 0, 13)));
            previousRaw = raw;
        }

        string text = string.Join(_newLine, lines) + _newLine;
        _fileSystem.WriteAllText(Path.Combine(outputFolder, FileName), text);
        return text;
    }

    /// <summary>Python <c>sum(q for c, q in raw.items() if c != "Desc_Water_C")</c> (Python 3.12+ float sum).</summary>
    private static double RawExcludingWater(TierResult result) =>
        PythonFloatSum.Of(result.RawInput.Where(kv => kv.Key != PlannerConstants.Water).Select(kv => kv.Value));

    /// <summary>Python <c>sum(reused.values())</c> (Python 3.12+ float sum).</summary>
    private static double Reused(TierResult result) => PythonFloatSum.Of(result.Reused.Values);
}
