using Satisfactory.Planner.Core.Identifiers;

namespace Satisfactory.Planner.Core.Model;

/// <summary>
/// A power generator pseudo-recipe that the Python builds in <c>Planner.__init__</c> (burning a nuclear fuel rod).
/// It generates <see cref="PowerOutputMw"/> per machine instead of consuming power.
/// </summary>
/// <param name="Id">The pseudo-recipe id (for example <c>Gen_Nuclear_Uranium</c>).</param>
/// <param name="Name">The display name (for example <c>Burn Uranium Fuel Rod</c>).</param>
/// <param name="IsAlternate">Always <see langword="false"/> for the built-in generators.</param>
/// <param name="TimeSeconds">Seconds per fuel rod.</param>
/// <param name="BuildingId">The generator building.</param>
/// <param name="Ingredients">The ingredients per cycle.</param>
/// <param name="Products">The products (waste) per cycle.</param>
/// <param name="BuildingName">The building name reported for the machines (Python <c>buildingName</c>).</param>
/// <param name="PowerOutputMw">The power generated by one machine, as a positive number.</param>
public sealed record GeneratorRecipe(
    RecipeId Id,
    string Name,
    bool IsAlternate,
    double TimeSeconds,
    BuildingId BuildingId,
    IReadOnlyList<ItemAmount> Ingredients,
    IReadOnlyList<ItemAmount> Products,
    string BuildingName,
    double PowerOutputMw)
    : Recipe(Id, Name, IsAlternate, TimeSeconds, BuildingId, Ingredients, Products);
