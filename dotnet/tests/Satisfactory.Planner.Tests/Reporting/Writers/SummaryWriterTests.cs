using Satisfactory.Planner.Core.Identifiers;
using Satisfactory.Planner.Core.Model;
using Satisfactory.Planner.Core.Tiers;
using Satisfactory.Planner.Reporting.Writers;
using Satisfactory.Planner.Tests.TestSupport;
using static Satisfactory.Planner.Tests.Reporting.Writers.WriterScenario;

namespace Satisfactory.Planner.Tests.Reporting.Writers;

[TestFixture]
public sealed class SummaryWriterTests
{
    private static readonly string[] HeaderLines =
    [
        "TIER SUMMARY (machines rounded up, 100% clock; extractors excluded; raw excludes water)",
        "",
        "Tier                   new items new machines  alts  reused     new MW  raw +/min | total machines   total MW nuclear MW total raw/min",
        "  (reused = machines' worth of spare capacity from earlier tiers put to work; MW = power used; nuclear MW = power generated by the plants built so far)",
        "",
    ];

    private InMemoryFileSystem _fileSystem = null!;

    [SetUp]
    public void SetUp() => _fileSystem = new InMemoryFileSystem();

    [TestCase("\n")]
    [TestCase("\r\n")]
    public void Write_ThreeTiers_MatchesPythonOutput(string newLine)
    {
        // Python main's summary loop fed the same tiers and totals.
        Recipe plain = RecipeOf("Recipe_IngotIron_C");
        Recipe alternate = RecipeOf("Recipe_Alternate_BoltedPlate_C");
        (TierResult, TierTotals)[] tiers =
        [
            (Tier(0, 6, [plain, plain], [], [(Water, 100.0), (OreIron, 145.4)]), new TierTotals(13, 52.0, 0.0)),
            (Tier(1, 4, [plain, alternate, alternate], [0.25, 0.3], [(OreIron, 100.0), (Water, 5000.0)]), new TierTotals(7, 1234.5, 0.0)),
            (Tier(8, 24, [plain], [20.64], [(OreIron, 12345678.9), (Coal, 0.5)]), new TierTotals(1001, 13162.4, 30000.0)),
        ];

        string text = new SummaryWriter(_fileSystem, newLine).Write(tiers, OutputFolder);

        string expected = Text(
            newLine,
            [
                .. HeaderLines,
                "Tier 0 - Onboarding            6           13     0     0.0         52        145 |             13         52          0           145",
                "Tier 1                         4            7     2     0.6      1,234        -45 |             20      1,286          0           100",
                "Tier 8                        24         1001     0    20.6     13,162 12,345,579 |           1021     14,449     30,000    12,345,679",
            ]);
        Assert.Multiple(() =>
        {
            Assert.That(text, Is.EqualTo(expected));
            Assert.That(_fileSystem.ReadAllText(Path.Combine(OutputFolder, "summary.txt")), Is.EqualTo(expected));
        });
    }

    [Test]
    public void Write_HeaderMatchesTheGoldenSummary()
    {
        string text = new SummaryWriter(_fileSystem, "\n").Write([], OutputFolder);

        string[] golden = File.ReadAllLines(Path.Combine(RepositoryPaths.GoldenOutput, "summary.txt"));
        Assert.Multiple(() =>
        {
            Assert.That(text, Is.EqualTo(Text("\n", HeaderLines)));
            Assert.That(golden[..5], Is.EqualTo(HeaderLines));
        });
    }

    [Test]
    public void Write_ReusedAndRaw_UsePythonCompensatedFloatSum()
    {
        // Python 3.12+ sum() of floats is compensated: sum([1.0, 1e16, -1e16]) is 1.0 (plain addition gives 0.0) and
        // sum([1e16, 1.0, 1.0]) is 1.0000000000000002e16 (plain addition gives 1e16). Water is left out of raw.
        TierResult result = Tier(
            2, 0, [], [1.0, 1e16, -1e16], [(Coal, 1e16), (Water, 5.0), (OreIron, 1.0), (IronIngot, 1.0)]);

        string text = new SummaryWriter(_fileSystem, "\n").Write([(result, new TierTotals(0, 0, 0))], OutputFolder);

        Assert.That(
            text.Split('\n')[5],
            Is.EqualTo("Tier 2                         0            0     0     1.0          0 10,000,000,000,000,002 |              0          0          0 10,000,000,000,000,002"));
    }

    [Test]
    public void Write_RejectsNulls()
    {
        var writer = new SummaryWriter(_fileSystem, "\n");

        Assert.Multiple(() =>
        {
            Assert.That(() => new SummaryWriter(null!, "\n"), Throws.ArgumentNullException);
            Assert.That(() => new SummaryWriter(_fileSystem, null!), Throws.ArgumentNullException);
            Assert.That(() => writer.Write(null!, OutputFolder), Throws.ArgumentNullException);
            Assert.That(() => writer.Write([], null!), Throws.ArgumentNullException);
        });
    }

    private static TierResult Tier(
        int tier, int newItems, Recipe[] newMachines, double[] reused, (ItemId Item, double Rate)[] raw)
    {
        var machines = new OrderedDictionary<RecipeId, int>();
        var recipes = new OrderedDictionary<RecipeId, Recipe>();
        for (int index = 0; index < newMachines.Length; index++)
        {
            Recipe recipe = newMachines[index] with { Id = new RecipeId($"R{index}") };
            machines.Add(recipe.Id, 1);
            recipes.Add(recipe.Id, recipe);
        }

        var reusedByItem = new OrderedDictionary<ItemId, double>();
        for (int index = 0; index < reused.Length; index++)
        {
            reusedByItem.Add(new ItemId($"Item{index}"), reused[index]);
        }

        return Minimal() with
        {
            Tier = tier,
            NewItems = Enumerable.Range(0, newItems).Select(i => new ItemId($"New{i}")).ToList(),
            NewMachines = machines,
            Recipes = recipes,
            Reused = reusedByItem,
            RawInput = Ordered(raw.Select(r => (r.Item, r.Rate)).ToArray()),
        };
    }
}
